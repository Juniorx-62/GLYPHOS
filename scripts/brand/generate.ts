/**
 * Builds the brand files from brand/geometry.ts and brand/tokens/source.ts:
 *
 *   brand/tokens/tokens.css · tailwind.css · tokens.json
 *   brand/logo/glyphos-{symbol,wordmark}{,-inverse,-mono}.svg · glyphos-app-icon.svg
 *   public/favicon.svg · public/manifest.webmanifest
 *   with --png (needs Chrome): public/favicon.ico · favicon-32.png · apple-touch-icon.png ·
 *   icon-192.png · icon-512.png · icon-maskable-512.png · images/og-glyphos.png
 *
 *   npm run brand              text files
 *   npm run brand -- --png     text files and the PNG/ICO images
 *   npm run check:brand        fails when a text file differs from its source
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { STROKE, gPath, gSquare, wordmark } from '../../brand/geometry.ts'
import { brand, colorTokenMeta, colorTokenNames, colors, controls, fonts, motion, radius, shadows, textScale } from '../../brand/tokens/source.ts'
import { ROOT, parseArgs, rel } from '../lib/catalog.ts'

const { flags } = parseArgs()
const HEADER = '/* Generated by scripts/brand/generate.ts from brand/tokens/source.ts — do not edit by hand. */'
const out = new Map<string, string>()

/* ------------------------------------------------------------- tokens */

const themeBlock = (theme: 'light' | 'dark') =>
  [
    ...colorTokenNames.map((n) => `  --color-${n}: ${colors[theme][n]};`),
    ...Object.entries(shadows[theme]).map(([k, v]) => `  --shadow-${k}: ${v};`),
    `  color-scheme: ${theme};`,
  ].join('\n')

out.set(
  'brand/tokens/tokens.css',
  `${HEADER}

/* Runtime values per theme. <html data-theme> is set before the first paint
   (see src/components/layout/theme.ts). Any subtree can switch theme by
   carrying data-theme itself (the light/dark previews do). */
:root,
[data-theme='light'] {
${themeBlock('light')}
}

[data-theme='dark'] {
${themeBlock('dark')}
}
`,
)

out.set(
  'brand/tokens/tailwind.css',
  `${HEADER}

/* Registers the brand tokens with Tailwind CSS 4. The default palette, type
   scale and shadows are removed: only brand values exist as utilities. */
@theme {
  --color-*: initial;
  --color-white: #ffffff;
  --color-black: #000000;
  --color-transparent: transparent;
  --color-current: currentColor;
${colorTokenNames.map((n) => `  --color-${n}: ${colors.light[n]};`).join('\n')}

  --font-sans: ${fonts.sans};
  --font-mono: ${fonts.mono};

  --text-*: initial;
${Object.entries(textScale)
  .map(([k, [size, lh, ls]]) => `  --text-${k}: ${size};\n  --text-${k}--line-height: ${lh};\n  --text-${k}--letter-spacing: ${ls};`)
  .join('\n')}

  --radius-*: initial;
${Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v};`).join('\n')}

  --shadow-*: initial;
${Object.entries(shadows.light).map(([k, v]) => `  --shadow-${k}: ${v};`).join('\n')}

  --ease-standard: ${motion.ease};
  --ease-out: ${motion.easeOut};
  --duration-fast: ${motion.fast};
  --duration-base: ${motion.base};
  --duration-slow: ${motion.slow};

  --spacing-control-sm: ${controls.sm};
  --spacing-control-md: ${controls.md};
  --spacing-control-lg: ${controls.lg};
}
`,
)

out.set(
  'brand/tokens/tokens.json',
  JSON.stringify(
    {
      $description: 'GLYPHOS design tokens. Generated from brand/tokens/source.ts.',
      color: Object.fromEntries(colorTokenNames.map((n) => [n, { light: colors.light[n], dark: colors.dark[n], description: colorTokenMeta[n] }])),
      brand,
      font: fonts,
      text: textScale,
      radius,
      shadow: shadows,
      motion,
      controls,
    },
    null,
    2,
  ) + '\n',
)

/* ------------------------------------------------------------- logos */

const svgOpen = (w: number, h: number, title: string) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" role="img" aria-label="${title}"><title>${title}</title>`
const strokeAttrs = (color: string) => `fill="none" stroke="${color}" stroke-width="${STROKE}" stroke-linecap="round" stroke-linejoin="round"`
const square = (sq: ReturnType<typeof gSquare>, color: string) =>
  `<rect x="${sq.x}" y="${sq.y}" width="${sq.size}" height="${sq.size}" rx="${sq.rx}" fill="${color}"/>`

function symbol(ink: string, mark: string) {
  return `${svgOpen(24, 24, 'GLYPHOS')}<path d="${gPath(4)}" ${strokeAttrs(ink)}/>${square(gSquare(4), mark)}</svg>\n`
}

function wordmarkSvg(ink: string, mark: string) {
  const w = wordmark(2)
  const width = Math.ceil(w.width + 4)
  return `${svgOpen(width, 24, 'GLYPHOS')}<path d="${w.d}" ${strokeAttrs(ink)}/>${square(w.square, mark)}</svg>\n`
}

function appIcon(size = 512, { maskable = false } = {}) {
  // The symbol on an ink tile. Maskable icons keep the mark inside the 80% safe zone.
  const scale = maskable ? 0.5 : 0.62
  const s = (size * scale) / 24
  const off = (size - 24 * s) / 2
  const rxTile = maskable ? 0 : size * 0.22
  return `${svgOpen(size, size, 'GLYPHOS')}<rect width="${size}" height="${size}" rx="${rxTile}" fill="${brand.ink}"/><g transform="translate(${off} ${off}) scale(${s})"><path d="${gPath(4)}" ${strokeAttrs(brand.paper)}/>${square(gSquare(4), brand.rubricOnInk)}</g></svg>\n`
}

out.set('brand/logo/glyphos-symbol.svg', symbol(brand.ink, brand.rubric))
out.set('brand/logo/glyphos-symbol-inverse.svg', symbol(brand.paper, brand.rubricOnInk))
out.set('brand/logo/glyphos-symbol-mono.svg', symbol('currentColor', 'currentColor'))
out.set('brand/logo/glyphos-wordmark.svg', wordmarkSvg(brand.ink, brand.rubric))
out.set('brand/logo/glyphos-wordmark-inverse.svg', wordmarkSvg(brand.paper, brand.rubricOnInk))
out.set('brand/logo/glyphos-wordmark-mono.svg', wordmarkSvg('currentColor', 'currentColor'))
out.set('brand/logo/glyphos-app-icon.svg', appIcon(512))
out.set('public/favicon.svg', appIcon(64))

out.set(
  'public/manifest.webmanifest',
  JSON.stringify(
    {
      name: 'GLYPHOS — biblioteca de ícones',
      short_name: 'GLYPHOS',
      description: 'Ícones SVG originais, pesquisáveis em português e inglês, para copiar e exportar.',
      lang: 'pt-BR',
      start_url: '/',
      display: 'standalone',
      background_color: colors.dark.background,
      theme_color: colors.dark.background,
      icons: [
        { src: '/icon-192.png', sizes: '192x192', type: 'image/png' },
        { src: '/icon-512.png', sizes: '512x512', type: 'image/png' },
        { src: '/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        { src: '/favicon.svg', sizes: 'any', type: 'image/svg+xml' },
      ],
    },
    null,
    2,
  ) + '\n',
)

/* ------------------------------------------------------------- write / check */

if (flags.has('check')) {
  const stale = [...out].filter(([file, text]) => !existsSync(join(ROOT, file)) || readFileSync(join(ROOT, file), 'utf8') !== text).map(([f]) => f)
  if (stale.length) {
    console.error(`Arquivos da marca desatualizados: ${stale.join(', ')}. Rode npm run brand.`)
    process.exit(1)
  }
  console.log('Marca em dia.')
  process.exit(0)
}

for (const [file, text] of out) {
  mkdirSync(dirname(join(ROOT, file)), { recursive: true })
  writeFileSync(join(ROOT, file), text)
}
console.log(`${out.size} arquivos da marca gerados.`)

/* ------------------------------------------------------------- images */

if (flags.has('png')) {
  const { launch } = await import('../lib/chrome.mjs')
  const geist = pathToFileURL(join(ROOT, 'node_modules/@fontsource-variable/geist/files/geist-latin-wght-normal.woff2')).href
  const tmpDir = join(ROOT, 'tmp/brand')
  mkdirSync(tmpDir, { recursive: true })
  const chrome = await launch()
  const shoot = async (html: string, width: number, height: number) => {
    const file = join(tmpDir, `shot-${width}x${height}.html`)
    writeFileSync(file, `<!doctype html><meta charset="utf-8"><style>@font-face{font-family:Geist;src:url(${geist})}html,body{margin:0;background:transparent}</style>${html}`)
    const page = await chrome.newPage({ width, height })
    await page.goto(pathToFileURL(file).href, { waitMs: 300 })
    await page.call('Emulation.setDefaultBackgroundColorOverride', { color: { r: 0, g: 0, b: 0, a: 0 } })
    const png = await page.screenshot()
    await page.close()
    return png
  }
  try {
    const icon = (size: number, maskable = false) => shoot(appIcon(size, { maskable }), size, size)
    const files: Array<[string, Buffer]> = [
      ['public/favicon-32.png', await icon(32)],
      ['public/apple-touch-icon.png', await shoot(appIcon(180).replace(/rx="[\d.]+"/, 'rx="0"'), 180, 180)],
      ['public/icon-192.png', await icon(192)],
      ['public/icon-512.png', await icon(512)],
      ['public/icon-maskable-512.png', await icon(512, true)],
    ]
    // favicon.ico: one 48 × 48 PNG inside an ICO container (PNG entries are valid since Windows Vista).
    const png48 = await icon(48)
    const ico = Buffer.alloc(22)
    ico.writeUInt16LE(0, 0)
    ico.writeUInt16LE(1, 2)
    ico.writeUInt16LE(1, 4)
    ico.writeUInt8(48, 6)
    ico.writeUInt8(48, 7)
    ico.writeUInt16LE(1, 10)
    ico.writeUInt16LE(32, 12)
    ico.writeUInt32LE(png48.length, 14)
    ico.writeUInt32LE(22, 18)
    files.push(['public/favicon.ico', Buffer.concat([ico, png48])])

    // Share image: the wordmark on ink, the tagline and a band of real catalogue icons.
    const outline = join(ROOT, 'public/svg/outline')
    const sample = existsSync(outline)
      ? readdirSync(outline)
          .filter((_, i) => i % 7 === 0)
          .slice(0, 36)
          .map((f) => readFileSync(join(outline, f), 'utf8').replace(/width="24" height="24"/, 'width="40" height="40"'))
      : []
    const w = wordmark(2)
    const og = `<div style="width:1200px;height:630px;background:${brand.ink};color:${brand.paper};font-family:Geist,sans-serif;position:relative;overflow:hidden">
      <div style="position:absolute;inset:auto 0 0 0;height:250px;display:grid;grid-template-columns:repeat(18,1fr);gap:28px 0;padding:0 40px;color:#55554f;align-content:start">${sample.join('')}</div>
      <div style="position:absolute;inset:auto 0 0 0;height:250px;background:linear-gradient(${brand.ink},transparent 45%)"></div>
      <div style="position:absolute;left:80px;top:96px">
        <svg width="${Math.ceil((w.width + 4) * 4)}" height="96" viewBox="0 0 ${Math.ceil(w.width + 4)} 24"><path d="${w.d}" ${strokeAttrs(brand.paper)}/>${square(w.square, brand.rubricOnInk)}</svg>
        <p style="margin:40px 0 0;font-size:40px;line-height:1.2;font-weight:500;letter-spacing:-0.02em;max-width:900px">Ícones SVG originais, pesquisáveis em português e inglês.</p>
        <p style="margin:16px 0 0;font-size:24px;color:#a2a29a">Copie em SVG, JSX ou CSS · exporte em PNG · licença MIT</p>
      </div></div>`
    files.push(['public/images/og-glyphos.png', await shoot(og, 1200, 630)])
    for (const [file, data] of files) {
      mkdirSync(dirname(join(ROOT, file)), { recursive: true })
      writeFileSync(join(ROOT, file), data)
      console.log(rel(join(ROOT, file)))
    }
  } finally {
    await chrome.close()
  }
}
